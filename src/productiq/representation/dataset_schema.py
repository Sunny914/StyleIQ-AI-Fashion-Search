"""Schema and contract constants for the Phase 3.11 representation dataset artifact."""

from __future__ import annotations

from data.export.schema import (
    CHECKSUM_ALGORITHM,
    PROCESSED_DATASET_NAME,
    PROCESSED_PARQUET_FILENAME,
)
from productiq.representation.filtering import FILTERING_REPRESENTATION_FIELD_ORDER
from productiq.representation.ontology import MULTI_VALUE_REPRESENTATION_FIELDS
from productiq.representation.serializers import REPRESENTATION_FIELD_ORDER

REPRESENTATION_DATASET_SCHEMA_VERSION = "1.0.0"
REPRESENTATION_DATASET_NAME = "product_representations"
REPRESENTATION_DATASET_FORMAT = "parquet"
REPRESENTATION_PARQUET_FILENAME = "product_representations.parquet"
REPRESENTATION_MANIFEST_FILENAME = "product_representations.manifest.json"
REPRESENTATION_PIPELINE_PHASE = "3.11"

SOURCE_CATALOG_DATASET_NAME = PROCESSED_DATASET_NAME
SOURCE_CATALOG_PARQUET_FILENAME = PROCESSED_PARQUET_FILENAME

PRODUCT_TEXT_COLUMN = "product_text"
LEXICAL_TEXT_COLUMN = "lexical_text"
SEMANTIC_TEXT_COLUMN = "semantic_text"

TEXT_COLUMNS: tuple[str, ...] = (
    PRODUCT_TEXT_COLUMN,
    LEXICAL_TEXT_COLUMN,
    SEMANTIC_TEXT_COLUMN,
)

# Filtering fields not already present on ProductRepresentation.
FILTERING_METADATA_COLUMNS: tuple[str, ...] = tuple(
    column
    for column in FILTERING_REPRESENTATION_FIELD_ORDER
    if column not in REPRESENTATION_FIELD_ORDER
)

REPRESENTATION_DATASET_MULTI_VALUE_COLUMNS: frozenset[str] = MULTI_VALUE_REPRESENTATION_FIELDS

REPRESENTATION_DATASET_COLUMN_ORDER: tuple[str, ...] = (
    *REPRESENTATION_FIELD_ORDER,
    *TEXT_COLUMNS,
    *FILTERING_METADATA_COLUMNS,
)

REPRESENTATION_DATASET_COLUMN_COUNT = len(REPRESENTATION_DATASET_COLUMN_ORDER)

assert REPRESENTATION_DATASET_COLUMN_ORDER[0] == "product_id"
assert FILTERING_METADATA_COLUMNS[0] == "source"

